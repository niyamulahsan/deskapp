import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Project root: src/core/api -> ../../..
const PROJECT_ROOT = path.resolve(__dirname, "..", "..", "..");
const MODULES_DIR = path.join(PROJECT_ROOT, "src", "modules");
const OUT_FILE = path.join(PROJECT_ROOT, "src", "core", "api", "bindings.generated.ts");

interface ControllerEntry {
  module: string;
  controller: string;
  importPath: string;
}

function collectControllers(): ControllerEntry[] {
  const entries: ControllerEntry[] = [];
  if (!fs.existsSync(MODULES_DIR)) return entries;

  for (const modDirent of fs.readdirSync(MODULES_DIR, { withFileTypes: true })) {
    if (!modDirent.isDirectory()) continue;
    const moduleName = modDirent.name;
    const controllersDir = path.join(MODULES_DIR, moduleName, "controllers");
    if (!fs.existsSync(controllersDir)) continue;

    for (const file of fs.readdirSync(controllersDir, { withFileTypes: true })) {
      if (!file.isFile() || !file.name.endsWith(".controller.ts")) continue;
      const controller = file.name.replace(/\.controller\.ts$/, "");
      entries.push({
        module: moduleName,
        controller,
        importPath: `@/modules/${moduleName}/controllers/${controller}.controller`,
      });
    }
  }

  return entries.sort((a, b) =>
    `${a.module}.${a.controller}`.localeCompare(`${b.module}.${b.controller}`),
  );
}

function generate(): void {
  const controllers = collectControllers();
  const imports = controllers
    .map((c, i) => `import * as mod${i} from "${c.importPath}";`)
    .join("\n");
  const items = controllers
    .map((c, i) => `  { module: "${c.module}", controller: "${c.controller}", mod: mod${i} }`)
    .join(",\n");

  const content = `// AUTO-GENERATED by \`npm run maker -- bindings:gen\`. Do not edit.
// Regenerates the controller list so packaged builds don't rely on scanning
// the filesystem at runtime.

${imports || "// no controllers found"}

export interface GeneratedController {
  module: string;
  controller: string;
  mod: Record<string, unknown>;
}

export const GENERATED_CONTROLLERS: GeneratedController[] = [
${items}
];
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, content, "utf8");
  console.log(`[bindings:gen] wrote ${path.relative(PROJECT_ROOT, OUT_FILE)} (${controllers.length} controller(s))`);
}

function isMain(): boolean {
  try {
    return process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) generate();

export { collectControllers, generate };
