import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SRC_PATH = path.resolve(process.cwd(), "src");
const SCHEMA_PATH = path.join(SRC_PATH, "database", "schema.ts");

export function walkTs(dir: string, out: string[]): void {
  try {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walkTs(full, out);
      else if (entry.isFile() && (entry.name.endsWith(".ts") || entry.name.endsWith(".tsx"))) out.push(full);
    }
  } catch {
    // path does not exist - skip
  }
}

export function discoverModelFiles(srcPath = SRC_PATH): string[] {
  const modelFiles: string[] = [];
  const modulesDir = path.join(srcPath, "modules");
  const coreDir = path.join(srcPath, "core");

  if (fs.existsSync(modulesDir)) {
    for (const moduleDir of fs.readdirSync(modulesDir, { withFileTypes: true })) {
      if (!moduleDir.isDirectory()) continue;
      walkTs(path.join(moduleDir.name ? path.join(modulesDir, moduleDir.name) : "", "database", "models"), modelFiles);
    }
  }
  // fix: above had a bug in my quick logic; do it clearly
  modelFiles.length = 0;
  if (fs.existsSync(modulesDir)) {
    for (const moduleDir of fs.readdirSync(modulesDir, { withFileTypes: true })) {
      if (!moduleDir.isDirectory()) continue;
      walkTs(path.join(modulesDir, moduleDir.name, "database", "models"), modelFiles);
    }
  }
  if (fs.existsSync(coreDir)) {
    for (const areaDir of fs.readdirSync(coreDir, { withFileTypes: true })) {
      if (!areaDir.isDirectory()) continue;
      walkTs(path.join(coreDir, areaDir.name, "database", "models"), modelFiles);
    }
  }
  return modelFiles.sort();
}

export function generateSchemaFile(srcPath = SRC_PATH, schemaPath = SCHEMA_PATH): string[] {
  const modelFiles = discoverModelFiles(srcPath);
  const modelExports = modelFiles
    .map((f) => {
      const rel = path.relative(srcPath, f).replace(/\\/g, "/");
      const ext = rel.endsWith(".tsx") ? ".tsx" : ".ts";
      const base = rel.slice(0, -ext.length);
      return `export * from "../${base}${ext}";`;
    })
    .join("\n");

  const content = `/**
 * schema.ts - GENERATED by \`npm run db:schema\`. Do NOT edit by hand.
 * Aggregates every module + core database/models/*.ts into one Drizzle schema.
 */

${modelExports || "export {};"}
`;
  fs.mkdirSync(path.dirname(schemaPath), { recursive: true });
  fs.mkdirSync(path.join(srcPath, "storage"), { recursive: true });
  fs.writeFileSync(schemaPath, content);
  return modelFiles;
}

function isMain(): boolean {
  try {
    const arg = process.argv[1];
    if (!arg) return false;
    return path.resolve(arg) === path.resolve(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  const found = generateSchemaFile();
  console.log(`[db:schema] wrote ${SCHEMA_PATH} (${found.length} model(s))`);
}
